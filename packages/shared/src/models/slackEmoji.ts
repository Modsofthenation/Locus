export function standardSlackEmoji(name: string): string | undefined {
  return STANDARD[name.toLowerCase()];
}

export const SLACK_QUICK_REACTIONS = [
  "+1",
  "heart",
  "eyes",
  "tada",
  "white_check_mark",
  "fire",
  "smile",
  "joy",
  "thinking_face",
  "wave",
  "clap",
  "cry",
] as const;

export function listSlackReactionNames(custom: SlackEmojiMap = {}, query = ""): string[] {
  const needle = query
    .trim()
    .toLowerCase()
    .replace(/^:+|:+$/g, "");
  const customNames = Object.keys(custom);
  if (!needle) {
    const seen = new Set<string>();
    const out: string[] = [];
    for (const name of [...SLACK_QUICK_REACTIONS, ...customNames]) {
      if (seen.has(name)) continue;
      seen.add(name);
      out.push(name);
      if (out.length >= 36) break;
    }
    return out;
  }
  const names = new Set([...Object.keys(STANDARD), ...customNames]);
  return [...names].filter((name) => name.includes(needle)).slice(0, 48);
}

export function resolveSlackEmojiMap(raw: SlackEmojiMap): SlackEmojiMap {
  const out: SlackEmojiMap = {};
  for (const name of Object.keys(raw)) {
    const url = resolveAlias(raw, name, 0);
    if (url && isSafeEmojiUrl(url)) out[name] = url;
  }
  return out;
}

export function applySlackEmoji(html: string, custom: SlackEmojiMap = {}): string {
  return html.replace(
    /(<code\b[\s\S]*?<\/code>|<pre\b[\s\S]*?<\/pre>)|:([a-z0-9_+-]+)(?::skin-tone-[2-6])?:/gi,
    (full, preserved: string | undefined, name: string | undefined) => {
      if (preserved) return preserved;
      const key = (name ?? "").toLowerCase();
      if (!key) return full;
      const customUrl = custom[key];
      if (customUrl && isSafeEmojiUrl(customUrl)) {
        return `<img class="slack-emoji" src="${escapeAttr(customUrl)}" alt=":${key}:" title=":${key}:">`;
      }
      const unicode = STANDARD[key];
      if (unicode) return `<span class="slack-emoji-char" title=":${key}:">${unicode}</span>`;
      return full;
    },
  );
}

export function isSafeEmojiUrl(url: string): boolean {
  try {
    const parsed = new URL(url);
    if (parsed.protocol !== "https:") return false;
    if (parsed.username || parsed.password) return false;
    return true;
  } catch {
    return false;
  }
}

function resolveAlias(raw: SlackEmojiMap, name: string, hops: number): string | undefined {
  if (hops > 8) return undefined;
  const value = raw[name];
  if (!value) return undefined;
  if (value.startsWith("alias:")) return resolveAlias(raw, value.slice("alias:".length), hops + 1);
  return value;
}

function escapeAttr(value: string): string {
  return value.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
}
