export type ThemeId = (typeof THEME_IDS)[number];

export const DEFAULT_THEME: ThemeId = "ember";

/** Themes the Appearance page designs against. The rest stay in See all. */
export const FEATURED_THEME_IDS: readonly ThemeId[] = ["ember", "midnight", "paper", "contrast"];

export interface ThemeOption {
  id: ThemeId;
  name: string;
  summary: string;
  scheme: "dark" | "light";
  swatches: [string, string, string, string];
  /** Local photo drawn behind the chat pane. */
  chatScene?: boolean;
  /** High-contrast palettes, filtered separately from dark/light. */
  contrast?: boolean;
  /** Gradient washes, filtered separately from dark/light/contrast. */
  gradient?: boolean;
}

export type ThemeFamily = "dark" | "light" | "contrast" | "gradient";
export type ThemeFilter = "all" | ThemeFamily;

export function themeFamily(opt: ThemeOption): ThemeFamily {
  if (opt.contrast) return "contrast";
  if (opt.gradient) return "gradient";
  return opt.scheme;
}

export function themeFamilyLabel(family: ThemeFamily): string {
  if (family === "contrast") return "Contrast";
  if (family === "gradient") return "Gradient";
  return family === "light" ? "Light" : "Dark";
}

export function filterThemeOptions(filter: ThemeFilter): ThemeOption[] {
  if (filter === "all") return THEME_OPTIONS;
  return THEME_OPTIONS.filter((opt) => themeFamily(opt) === filter);
}

