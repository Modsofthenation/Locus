export interface ThemeOption {
  id: ThemeId;
  name: string;
  summary: string;
  scheme: "dark" | "light";
  swatches: [string, string, string, string];
  /** Local photo drawn behind the chat pane. */
  chatScene?: boolean;
  /** High-contrast palettes, filtered separately from dark/light. */
  contrast?: boolean;
  /** Gradient washes, filtered separately from dark/light/contrast. */
  gradient?: boolean;
  /** Terminal-window chrome (titlebar, scanlines, mono type), grouped as Terminal. */
  terminal?: boolean;
  /** A structural look (borders, shadows, type, surfaces), grouped by style. */
  style?: ThemeStyle;
  /** Compiled from an engine spec (craftedThemes.ts); grouped as Crafted and remixable. */
  crafted?: boolean;
  /** Follows the system light/dark setting; `scheme` is the one it was designed in. */
  adaptive?: boolean;
}

