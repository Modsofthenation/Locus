export const NODE_LIBRARY_BY_TYPE = Object.fromEntries(
  NODE_LIBRARY.map((item) => [item.type, item]),
) as Record<NodeType, NodeLibraryItem>;

export const NODE_CATEGORIES: { id: NodeCategory; label: string }[] = [
  { id: 'agent', label: 'Agent' },
  { id: 'tool', label: 'Tools' },
  { id: 'logic', label: 'Logic' },
  { id: 'data', label: 'Data' },
  { id: 'human', label: 'Human Interaction' },
  { id: 'skill', label: 'Skills' },
];

export function createNodeData(type: NodeType, labelOverride?: string): WorkflowNodeData {
  const item = NODE_LIBRARY_BY_TYPE[type];
  if (!item) {
    throw new Error(`Unknown node type: ${type}`);
  }
  const config = structuredClone(item.defaultConfig);
  return {
    label: labelOverride ?? item.label,
    nodeType: type,
    category: item.category,
    description: item.description,
    status: 'default',
    inputs: structuredClone(item.defaultInputs),
    outputs: structuredClone(item.defaultOutputs),
    config,
    configSummary: item.configSummary?.(config),
    disabled: false,
    validationErrors: [],
  };
}
